"""Предобработка текста. Одинаково применяется к документам и к запросам.

Три режима (настройка `mode`), чтобы сравнивать версии поиска по одной настройке:
- "plain" — нижний регистр, без пунктуации, слова сравниваются буквально (как в методичке);
- "stem"  — plain + простое отсечение русских окончаний («москве» и «москва» → «москв»);
- "stem_stop" — stem + удаление служебных слов («как», «где», «в», «ли» ...).
"""
import re

TOKEN_RE = re.compile(r"[a-zа-яё0-9]+")

# Окончания, от длинных к коротким. Это не полноценный стеммер, а учебное
# приближение: отрезаем одно окончание, если остаётся основа >= 3 букв.
ENDINGS = sorted({
    "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими", "ться", "тся",
    "ешь", "ете", "ает", "яет", "ует", "ают", "яют", "ать", "ять", "ить", "еть",
    "ой", "ей", "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие", "ом", "ем",
    "ам", "ям", "ах", "ях", "ов", "ев", "ую", "юю", "ым", "им", "ут", "ют",
    "ы", "и", "а", "я", "о", "е", "у", "ю", "ь", "й",
}, key=len, reverse=True)
MIN_STEM = 3

STOPWORDS = {
    "а", "в", "во", "и", "к", "ко", "на", "о", "об", "от", "по", "с", "со", "у", "из", "за", "для",
    "до", "не", "ни", "ли", "же", "бы", "или", "но", "что", "как", "где", "когда", "какой", "какая",
    "какие", "каких", "какое", "каком", "который", "которые", "это", "этот", "эта", "есть", "можно",
    "ли", "мне", "я", "мы", "вы", "ты", "он", "она", "они", "их", "его", "её", "ее", "там", "тут",
    "сколько", "чтобы", "так", "уже", "ещё", "еще", "при", "без", "под", "над", "про", "через",
    "всех", "все", "всё", "весь", "очень",
}


def tokens(text: str) -> list[str]:
    """Нижний регистр, ё→е, только буквы и цифры (пунктуация удаляется)."""
    return TOKEN_RE.findall(text.lower().replace("ё", "е"))


def stem(word: str) -> str:
    if word.isdigit():
        return word
    for ending in ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM:
            return word[: -len(ending)]
    return word


def analyze(text: str, mode: str = "stem_stop") -> list[str]:
    words = tokens(text)
    if mode == "plain":
        return words
    if mode == "stem_stop":
        words = [w for w in words if w not in STOPWORDS]
    elif mode != "stem":
        raise ValueError(f"unknown mode: {mode}")
    return [stem(w) for w in words]
